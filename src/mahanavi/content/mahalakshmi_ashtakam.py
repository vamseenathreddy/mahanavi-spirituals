def quad(verse: str) -> str:
    """Two printed lines -> four pada lines so the card text stays large."""
    out: list[str] = []
    for ln in verse.split("\n"):
        words, mark = ln.rsplit(" ", 1)[0].split(" "), ln.rsplit(" ", 1)[1]
        cut = (len(words) + 1) // 2
        out += [" ".join(words[:cut]), " ".join(words[cut:]) + " " + mark]
    return "\n".join(out)
